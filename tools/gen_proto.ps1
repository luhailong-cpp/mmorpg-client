<#
.SYNOPSIS
    Generate C# protobuf classes from the server mmorpg repo's proto tree.

.DESCRIPTION
    Invokes protoc against the proto/ tree of the authoritative C++/Go server
    repository and emits .cs files into Assets/Scripts/Proto/Generated/.
    Proto files are discovered automatically (no manual file list to maintain):
      1. Client RPC roots parsed from Assets/Scripts/Net/Generated/Rpc/*.cs
         headers ("Generated by protogen from <path>.proto.") + fixed wire
         envelope seeds (message.proto / rpc_message.proto), recursively
         expanded along proto `import` directives.
      2. All tip error enums under generated/code/proto/tip/*_tip.proto.
    Run server `dev.bat proto` (or `dev.bat gen` when Tip.xlsx/tables changed)
    BEFORE running this script so Rpc/*.cs and tip protos are up to date.

.PARAMETER ProtoRoot
    Path to the authoritative C++/Go server repo root. When omitted, auto-probes
    sibling directories (xuanming-server-mmo-cpp, xuanming-server-mmo, mmorpg)
    for proto/message_id.txt + go/shared/generated/tip/faults.go.

.PARAMETER Protoc
    Path to a protoc executable. When omitted, prefers the server repo's
    third_party/protobuf/install_vs2026_dbg/bin/protoc.exe, else `protoc` on PATH.

.EXAMPLE
    pwsh -File tools/gen_proto.ps1
    pwsh -File tools/gen_proto.ps1 -ProtoRoot ../xuanming-server-mmo-cpp
#>
param(
    [string]$ProtoRoot = "",
    [string]$Protoc = ""
)

$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$repoRoot  = (Resolve-Path (Join-Path $scriptDir "..")).Path
$outDir    = Join-Path $repoRoot "Assets/Scripts/Proto/Generated"
$rpcDir    = Join-Path $repoRoot "Assets/Scripts/Net/Generated/Rpc"

if ([string]::IsNullOrWhiteSpace($ProtoRoot)) {
    foreach ($candidate in @('xuanming-server-mmo-cpp', 'xuanming-server-mmo', 'mmorpg')) {
        $probe = [System.IO.Path]::GetFullPath((Join-Path $repoRoot "../$candidate"))
        if ((Test-Path -LiteralPath (Join-Path $probe 'proto/message_id.txt')) -and
            (Test-Path -LiteralPath (Join-Path $probe 'go/shared/generated/tip/faults.go'))) {
            $ProtoRoot = $probe
            break
        }
    }
    if ([string]::IsNullOrWhiteSpace($ProtoRoot)) {
        throw "未找到同级权威服务端仓（已探测 ../xuanming-server-mmo-cpp、../xuanming-server-mmo、../mmorpg）；请显式传入 -ProtoRoot。"
    }
}
$ProtoRoot = (Resolve-Path -LiteralPath $ProtoRoot).Path

if ([string]::IsNullOrWhiteSpace($Protoc)) {
    $repoProtoc = Join-Path $ProtoRoot 'third_party/protobuf/install_vs2026_dbg/bin/protoc.exe'
    $Protoc = if (Test-Path -LiteralPath $repoProtoc) { $repoProtoc } else { 'protoc' }
}

if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }

# ── 自动扫描客户端需要的 .proto（服务端 Rpc 桩入口 + 传输信封种子 → 递归 import + 全部 tip 枚举）──
$merchantProto = 'proto/scene/player_mystery_merchant.proto'
$merchantTip   = 'generated/code/proto/tip/mystery_merchant_error_tip.proto'
$merchantPresent = @($merchantProto, $merchantTip | Where-Object { Test-Path -LiteralPath (Join-Path $ProtoRoot $_) })
$skipMysteryMerchant = $false
if ($merchantPresent.Count -eq 0) {
    $skipMysteryMerchant = $true
    Write-Warning '[gen_proto] 当前服务端没有神秘商人协议；保留客户端已入库类型，消息号由gen_messageids.ps1生成未支持的0。'
} elseif ($merchantPresent.Count -ne 2) {
    throw '神秘商人协议与导表提示码不完整；请先完成服务端生成，不能发布部分契约。'
}

if (-not (Test-Path -LiteralPath $rpcDir)) {
    throw "缺少客户端 RPC 调用桩目录：$rpcDir；请先在服务端运行 dev.bat proto。"
}
$rpcStubs = @(Get-ChildItem -LiteralPath $rpcDir -File -Filter '*.cs' | Sort-Object Name)
if ($rpcStubs.Count -eq 0) {
    throw "客户端 RPC 调用桩目录为空：$rpcDir；请先在服务端运行 dev.bat proto。"
}

# 固定底层传输信封种子（不挂在具体业务 service 下，但客户端网络层直连编解码需要）。
$seedProtos = New-Object 'System.Collections.Generic.List[string]'
$seedProtos.Add('proto/common/base/message.proto')
$seedProtos.Add('proto/common/base/rpc_message.proto')

foreach ($stub in $rpcStubs) {
    $stubText = Get-Content -LiteralPath $stub.FullName -Raw
    if ($stubText -notmatch 'Generated by protogen from ([^\s]+\.proto)\.') {
        throw "RPC 调用桩缺少 protogen 来源头，无法自动推断源 proto：$($stub.FullName)"
    }
    $relProto = $Matches[1].Replace('\', '/')
    if ($skipMysteryMerchant -and $relProto -eq $merchantProto) { continue }
    $seedProtos.Add($relProto)
}

$discovered = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
$queue = New-Object 'System.Collections.Generic.Queue[string]'
foreach ($seed in $seedProtos) {
    if ($discovered.Add($seed)) { $queue.Enqueue($seed) }
}

while ($queue.Count -gt 0) {
    $current = $queue.Dequeue()
    $fullPath = Join-Path $ProtoRoot $current
    if (-not (Test-Path -LiteralPath $fullPath)) {
        throw "自动扫描发现客户端依赖的 proto 不存在于服务端仓：$current（ProtoRoot=$ProtoRoot）"
    }
    $content = Get-Content -LiteralPath $fullPath -Raw
    foreach ($m in [regex]::Matches($content, '(?m)^\s*import\s+(?:public\s+)?"([^"]+\.proto)"\s*;')) {
        $imp = $m.Groups[1].Value.Replace('\', '/')
        if ($imp -like 'google/protobuf/*') { continue }
        if ($discovered.Add($imp)) { $queue.Enqueue($imp) }
    }
}

$tipDir = Join-Path $ProtoRoot 'generated/code/proto/tip'
if (-not (Test-Path -LiteralPath $tipDir)) {
    throw "缺少服务端导表 tip 目录：$tipDir；请先在服务端运行导表器（dev.bat gen）。"
}
$tipFiles = @(Get-ChildItem -LiteralPath $tipDir -Recurse -File -Filter '*_tip.proto' | Sort-Object FullName)
if ($tipFiles.Count -eq 0) {
    throw "服务端导表 tip 目录为空：$tipDir；请先在服务端运行导表器（dev.bat gen）。"
}
foreach ($tip in $tipFiles) {
    $relTip = $tip.FullName.Substring($ProtoRoot.Length).TrimStart('\', '/').Replace('\', '/')
    [void]$discovered.Add($relTip)
}

$files = @($discovered | Sort-Object)
# 组队恢复与补位已合为同一份正式契约；无论业务别名文件是否存在，都必须保护恢复字段及正式编号。
$teamSource = Get-Content -LiteralPath (Join-Path $ProtoRoot 'proto/team/team.proto') -Raw
function Get-TeamMessageBody([string]$name) {
    $pattern = '(?s)\bmessage\s+' + [regex]::Escape($name) + '\s*\{(.*?)\}'
    $match = [regex]::Match($teamSource, $pattern)
    if (-not $match.Success) { throw "组队协议兼容预检：缺少消息 $name" }
    return $match.Groups[1].Value
}
$teamContracts = @(
    @{ Message = 'GetMyTeamRequest'; Type = 'string'; Field = 'match_request_id'; Number = 2 }
    @{ Message = 'GetMyTeamRequest'; Type = 'bool'; Field = 'regroup'; Number = 3 }
    @{ Message = 'StartTeamMatchRequest'; Type = 'string'; Field = 'request_id'; Number = 3 }
    @{ Message = 'StartTeamMatchRequest'; Type = 'uint32'; Field = 'target_team_size'; Number = 4 }
    @{ Message = 'TeamResponse'; Type = 'TeamMatchIntent'; Field = 'match_intent'; Number = 3 }
    @{ Message = 'TeamMatchIntent'; Type = 'string'; Field = 'request_id'; Number = 1 }
    @{ Message = 'TeamMatchIntent'; Type = 'uint64'; Field = 'battle_id'; Number = 2 }
    @{ Message = 'TeamMatchIntent'; Type = 'uint32'; Field = 'state'; Number = 3 }
    @{ Message = 'TeamView'; Type = 'uint32'; Field = 'match_target_size'; Number = 13 }
    @{ Message = 'TeamView'; Type = 'uint64'; Field = 'match_queued_at_ms'; Number = 14 }
    @{ Message = 'TeamView'; Type = 'uint32'; Field = 'match_battle_config_id'; Number = 15 }
    @{ Message = 'TeamView'; Type = 'bool'; Field = 'match_fill_supported'; Number = 16 }
)
foreach ($contract in $teamContracts) {
    $body = Get-TeamMessageBody $contract.Message
    $pattern = '(?m)^\s*' + [regex]::Escape($contract.Type) + '\s+' + [regex]::Escape($contract.Field) +
        '\s*=\s*' + $contract.Number + '\s*;'
    if ($body -notmatch $pattern) {
        throw "组队协议兼容预检：缺少正式契约 $($contract.Message).$($contract.Field) = $($contract.Number) ($($contract.Type))；不能覆盖恢复或补位接口。"
    }
}
$teamBridge = Join-Path $repoRoot 'Assets/Scripts/Proto/TeamBackfillProtocol.cs'
if (Test-Path -LiteralPath $teamBridge) {
    $bridgeSource = Get-Content -LiteralPath $teamBridge -Raw
    $partialPattern = '(?m)^\s*(?:(?:public|internal|sealed|abstract|static)\s+)*partial\s+class\s+(?:GetMyTeamRequest|StartTeamMatchRequest|TeamView)\b'
    if ($bridgeSource -match $partialPattern) {
        throw '组队协议兼容预检：仍存在旧补位桥接partial成员；请移除桥接并使用正式生成字段，静态TeamBackfillProtocol别名可保留。'
    }
}

Push-Location $ProtoRoot
try {
    Write-Host "[gen_proto] proto root: $ProtoRoot"
    Write-Host "[gen_proto] protoc:     $Protoc"
    Write-Host "[gen_proto] output dir: $outDir"
    Write-Host "[gen_proto] discovered: $($files.Count) proto files (rpc stubs=$($rpcStubs.Count), tips=$($tipFiles.Count))"

    $args = @("--proto_path=$ProtoRoot", "--csharp_out=$outDir") + $files
    & $Protoc @args
    if ($LASTEXITCODE -ne 0) { throw "protoc exited with $LASTEXITCODE" }

    # protoc 不写 Unity 元数据；无效 GUID 会令 Unity 忽略源码，而直接 Roslyn 编译仍通过。
    $metadata = & (Join-Path $scriptDir 'sync_proto_script_meta.ps1') -GeneratedDirectory $outDir
    Write-Host "[gen_proto] Unity script metadata: checked=$($metadata.Checked), created=$($metadata.Created), repaired=$($metadata.Repaired)"

    Write-Host "[gen_proto] done. Generated files:"
    Get-ChildItem $outDir -Filter *.cs | ForEach-Object { Write-Host "  $($_.Name)" }
}
finally { Pop-Location }
